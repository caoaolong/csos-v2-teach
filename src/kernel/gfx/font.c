const uint8_t *fb_font_glyph(char c)
{
    uint8_t u = (uint8_t)c;

    if (u >= 'a' && u <= 'z')
        u -= 32;
    if (u < 0x20 || u > 0x5F)
        u = '?';
    return s_font[u - 0x20];
}
